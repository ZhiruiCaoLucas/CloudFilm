using System.Globalization;
using System.Net;
using System.Net.Http.Headers;
using System.Text;
using CloudFilm.Application.Imaging;
using Microsoft.AspNetCore.WebUtilities;

namespace CloudFilm.Infrastructure.Analysis;

/// <summary>
/// Rewrites a WADO-RS study into the upload the analysis service accepts.
/// </summary>
/// <remarks>
/// <para>
/// Two different multiparts meet here. The archive answers a study retrieval with
/// <c>multipart/related; type="application/dicom"</c> - one part per instance,
/// no part names, boundary in the response's own content type. The analysis
/// service accepts <c>multipart/form-data</c> with a repeated <c>files</c> field,
/// which is what an HTTP form upload looks like. They are not the same shape and
/// the body cannot simply be forwarded.
/// </para>
/// <para>
/// The rewrite happens while the response is being written, not before. This
/// content reads one part from the archive, writes one part to the analyser, and
/// moves on: at no point is the whole study held, and the largest thing in memory
/// is the copy buffer. A study is routinely hundreds of megabytes, and an
/// implementation that read it into a <c>byte[]</c> first would work in every test
/// and fail on the first real CT.
/// </para>
/// <para>
/// The consequence, stated because it is a real constraint rather than an
/// oversight: this content can be sent exactly once. The source is a live network
/// stream, and rewinding it is not possible. Any future retry has to begin by
/// asking the archive for the study again.
/// </para>
/// </remarks>
internal sealed class DicomFormDataContent : HttpContent
{
    /// <summary>The media type of a part the archive sends and this reads.</summary>
    private const string _dicomMediaType = "application/dicom";

    /// <summary>The field the analysis service expects each instance under.</summary>
    private const string _fileField = "files";

    /// <summary>
    /// How much of one instance is moved at a time.
    /// </summary>
    /// <remarks>
    /// Large enough that a syscall per kilobyte does not dominate a
    /// hundred-megabyte study, small enough to stay off the large object heap
    /// (which starts at 85,000 bytes) so that a service under load is not
    /// allocating a fresh gen-2 buffer per instance.
    /// </remarks>
    private const int _copyBufferBytes = 64 * 1024;

    private readonly StudyDownload _study;
    private readonly string _boundary;
    private readonly string? _studyInstanceUid;
    private readonly string _requestId;

    private int _instances;

    /// <summary>
    /// Initialises a new instance of the <see cref="DicomFormDataContent"/> class.
    /// </summary>
    /// <param name="study">The open study, still arriving from the archive.</param>
    /// <param name="studyInstanceUid">The study CloudFilm authorised, sent as a correlation value.</param>
    /// <param name="requestId">A correlation value for this call.</param>
    /// <param name="boundary">The boundary this request will use. Generated by the caller.</param>
    public DicomFormDataContent(
        StudyDownload study,
        string? studyInstanceUid,
        string requestId,
        string boundary)
    {
        _study = study;
        _studyInstanceUid = studyInstanceUid;
        _requestId = requestId;
        _boundary = boundary;

        // Quoted, because a boundary may legally contain characters that would
        // otherwise end the parameter.
        Headers.ContentType = new MediaTypeHeaderValue("multipart/form-data")
        {
            Parameters = { new NameValueHeaderValue("boundary", $"\"{boundary}\"") },
        };
    }

    /// <summary>
    /// Gets the number of DICOM instances written.
    /// </summary>
    /// <remarks>
    /// Only meaningful once the request has been sent. It exists so the caller can
    /// tell "the archive held no instances" from "the analyser refused what it was
    /// sent", which are different problems with the same symptom.
    /// </remarks>
    public int Instances => _instances;

    /// <inheritdoc />
    protected override async Task SerializeToStreamAsync(Stream stream, TransportContext? context) =>
        await SerializeToStreamAsync(stream, context, CancellationToken.None).ConfigureAwait(false);

    /// <inheritdoc />
    protected override async Task SerializeToStreamAsync(
        Stream stream,
        TransportContext? context,
        CancellationToken cancellationToken)
    {
        _instances = 0;

        MultipartReader reader = new(BoundaryOf(_study.ContentType), _study.Content);

        MultipartSection? section = await reader
            .ReadNextSectionAsync(cancellationToken)
            .ConfigureAwait(false);

        while (section is not null)
        {
            // Parts the archive sends that are not instances - a warning, say -
            // are skipped rather than forwarded. The analyser is given DICOM and
            // nothing else.
            if (IsDicom(section))
            {
                _instances++;

                await WriteFilePartAsync(stream, section.Body, _instances, cancellationToken)
                    .ConfigureAwait(false);
            }

            section = await reader.ReadNextSectionAsync(cancellationToken).ConfigureAwait(false);
        }

        if (_studyInstanceUid is not null)
        {
            await WriteFieldAsync(stream, "studyInstanceUid", _studyInstanceUid, cancellationToken)
                .ConfigureAwait(false);
        }

        await WriteFieldAsync(stream, "requestId", _requestId, cancellationToken).ConfigureAwait(false);

        await WriteAsciiAsync(stream, $"--{_boundary}--\r\n", cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    /// <remarks>
    /// Refuses to state a length, which makes the request chunked. The length is
    /// genuinely unknown: it depends on how many parts the archive sends and how
    /// large each is, and neither is known until the body has been read - by which
    /// point it is too late to put a number in a header.
    /// </remarks>
    protected override bool TryComputeLength(out long length)
    {
        length = 0;

        return false;
    }

    /// <summary>
    /// Reads the boundary out of the archive's content type.
    /// </summary>
    /// <exception cref="InvalidOperationException">
    /// If the response is not a multipart this can read. The message names the
    /// media type and nothing else - never a header value that could carry more.
    /// </exception>
    internal static string BoundaryOf(string contentType)
    {
        if (!MediaTypeHeaderValue.TryParse(contentType, out MediaTypeHeaderValue? parsed)
            || parsed.MediaType is null
            || !parsed.MediaType.StartsWith("multipart/", StringComparison.OrdinalIgnoreCase))
        {
            throw new InvalidOperationException(
                "The study was not returned as a multipart response and cannot be split into instances.");
        }

        // A boundary is often quoted, and MultipartReader wants it bare.
        string boundary = BoundaryParameter(parsed).Trim('"');

        if (string.IsNullOrWhiteSpace(boundary))
        {
            throw new InvalidOperationException(
                "The study's multipart response carries no boundary and cannot be split into instances.");
        }

        return boundary;
    }

    /// <summary>The value of the boundary parameter, or empty when absent.</summary>
    private static string BoundaryParameter(MediaTypeHeaderValue parsed)
    {
        foreach (NameValueHeaderValue parameter in parsed.Parameters)
        {
            if (string.Equals(parameter.Name, "boundary", StringComparison.OrdinalIgnoreCase))
            {
                return parameter.Value ?? string.Empty;
            }
        }

        return string.Empty;
    }

    /// <summary>
    /// Reports whether a part of the archive's response is a DICOM instance.
    /// </summary>
    /// <remarks>
    /// Decided from the part's own content type. A part that declares nothing is
    /// treated as DICOM, because that is what a study retrieval consists of and
    /// some servers omit the header on every part; a part that declares something
    /// else is skipped.
    /// </remarks>
    private static bool IsDicom(MultipartSection section)
    {
        string? declared = section.ContentType;

        return string.IsNullOrWhiteSpace(declared)
            || declared.Contains(_dicomMediaType, StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// Writes one instance as a form-data file part, copying it straight through.
    /// </summary>
    /// <remarks>
    /// The filename is an ordinal. Anything drawn from the instance would mean
    /// reading its tags, and a tag value can be a patient's name - which would put
    /// PHI in a header, in the analyser's request log, and in every proxy between
    /// the two.
    /// </remarks>
    private async Task WriteFilePartAsync(
        Stream destination,
        Stream instance,
        int ordinal,
        CancellationToken cancellationToken)
    {
        string filename = string.Create(CultureInfo.InvariantCulture, $"instance-{ordinal}.dcm");

        await WriteAsciiAsync(
                destination,
                $"--{_boundary}\r\n"
                + $"Content-Disposition: form-data; name=\"{_fileField}\"; filename=\"{filename}\"\r\n"
                + $"Content-Type: {_dicomMediaType}\r\n\r\n",
                cancellationToken)
            .ConfigureAwait(false);

        await instance.CopyToAsync(destination, _copyBufferBytes, cancellationToken).ConfigureAwait(false);

        await WriteAsciiAsync(destination, "\r\n", cancellationToken).ConfigureAwait(false);
    }

    /// <summary>Writes one ordinary form field.</summary>
    private async Task WriteFieldAsync(
        Stream destination,
        string name,
        string value,
        CancellationToken cancellationToken) =>
        await WriteAsciiAsync(
                destination,
                $"--{_boundary}\r\n"
                + $"Content-Disposition: form-data; name=\"{name}\"\r\n\r\n"
                + $"{value}\r\n",
                cancellationToken)
            .ConfigureAwait(false);

    /// <summary>
    /// Writes one piece of the multipart envelope.
    /// </summary>
    /// <remarks>
    /// UTF-8 rather than ASCII. Every value this writes is an identifier or a
    /// generated boundary, so the two encodings agree in practice; UTF-8 means a
    /// value that unexpectedly is not ASCII is transmitted rather than silently
    /// turned into question marks.
    /// </remarks>
    private static async Task WriteAsciiAsync(Stream destination, string text, CancellationToken cancellationToken)
    {
        byte[] bytes = Encoding.UTF8.GetBytes(text);

        await destination.WriteAsync(bytes, cancellationToken).ConfigureAwait(false);
    }
}
